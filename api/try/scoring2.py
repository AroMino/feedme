# ─── STEP 1 — PROFILE STRUCTURING ─────────────────────────

def structure_interests(interests: list) -> dict:
    """
    Ask Groq to classify interests as specific, generic, or redundant.
    Redundant = already fully covered by a more specific interest.
    """
    response = groq_client.chat.completions.create(
        model=GROQ_MODEL,
        messages=[
            {
                "role": "system",
                "content": (
                    "You are an interest taxonomy expert. "
                    "Respond ONLY with a valid JSON object, no explanation, no markdown."
                )
            },
            {
                "role": "user",
                "content": (
                    f"Given these user interests: {interests}\n\n"
                    "Classify each interest into exactly one category:\n"
                    "- specific: narrow, precise topic that cannot contain the others (e.g. 'machine learning', 'seed funding', 'artificial intelligence', 'startups')\n"
                    "- generic: broad umbrella term that contains or overlaps multiple other interests in the list (e.g. 'technology' contains 'AI' and 'startups')\n"
                    "- redundant: interest that is ENTIRELY covered by another MORE SPECIFIC interest already in the list. This is rare.\n\n"
                    "Rules:\n"
                    "- A generic term like 'tech innovation' or 'technology' should be classified as generic, not redundant\n"
                    "- A specific term like 'artificial intelligence' or 'startups' should be classified as specific, even if a generic term covers it\n"
                    "- Only mark as redundant if two interests mean almost exactly the same thing\n"
                    "- When in doubt, classify as specific\n\n"
                    "Return this exact JSON structure:\n"
                    "{\n"
                    '  "specific": ["interest1"],\n'
                    '  "generic": ["interest2"],\n'
                    '  "redundant": ["interest3"]\n'
                    "}"
                )
            }
        ],
        temperature=0.1,
        max_tokens=200
    )
    raw = response.choices[0].message.content.strip()
    # Strip markdown code fences if present
    raw = raw.replace("```json", "").replace("```", "").strip()
    return json.loads(raw)


# ─── STEP 2 — INTEREST ENRICHMENT ─────────────────────────

def enrich_interest(interest: str, kind: str) -> str:
    """
    Enrich an interest with keywords via Groq.
    Generic interests explicitly exclude terms already covered by specific ones.
    """
    specificity_note = (
        "Focus on very precise, narrow sub-topics, tools, models, companies, and techniques."
        if kind == "specific"
        else
        "Focus on broad domain labels, umbrella concepts, and adjacent fields. "
        "Avoid very technical or narrow terms — those are handled separately."
    )

    response = groq_client.chat.completions.create(
        model=GROQ_MODEL,
        messages=[
            {
                "role": "system",
                "content": (
                    "You are a keyword generation expert for semantic search.\n"
                    "Respond ONLY with a comma-separated list of keywords. "
                    "No sentences, no explanations, no numbering."
                )
            },
            {
                "role": "user",
                "content": (
                    f'Topic: "{interest}" ({kind})\n\n'
                    f"{specificity_note}\n\n"
                    "Generate 30 to 40 highly relevant keywords.\n"
                    "Format: keyword1, keyword2, keyword3, ..."
                )
            }
        ],
        temperature=0.3,
        max_tokens=300
    )
    return response.choices[0].message.content.strip()


# ─── STEP 3 — EMBEDDINGS ──────────────────────────────────

def get_embedding(text: str) -> np.ndarray:
    """Embedding via Gemini API"""
    time.sleep(0.5)  # avoid rate limit
    result = gemini_client.models.embed_content(
        model=MODEL_EMBED,
        contents=text
    )
    return np.array(result.embeddings[0].values)


def embed_keyword_list(keywords: list) -> np.ndarray:
    """Embed a list of keywords as a single joined text"""
    text = ", ".join(keywords)
    return get_embedding(text)


def build_profile_vectors(structured: dict, enriched: dict) -> dict:
    """
    Build one embedding vector per interest category (specific / generic).
    Each is a weighted average of enriched interest embeddings.
    Redundant interests are skipped.
    """
    vectors = {"specific": [], "generic": []}

    for kind in ["specific", "generic"]:
        for interest in structured.get(kind, []):
            emb = get_embedding(enriched[interest])
            vectors[kind].append(emb)

    # Average per category
    result = {}
    for kind in ["specific", "generic"]:
        if vectors[kind]:
            avg = np.mean(vectors[kind], axis=0)
            result[kind] = avg / np.linalg.norm(avg)
        else:
            result[kind] = None

    return result


# ─── STEP 4 — SCORING ─────────────────────────────────────

def cosine_similarity(v1: np.ndarray, v2: np.ndarray) -> float:
    norm = np.linalg.norm(v1) * np.linalg.norm(v2)
    return float(np.dot(v1, v2) / norm) if norm else 0.0


def score_article(article: dict, profile_vectors: dict) -> dict:
    """
    Multi-dimensional scoring:
    - specific_score : article.specific topics vs profile.specific vector
    - generic_score  : article.generic topics vs profile.generic vector
    - importance     : global importance weight
    """

    # Embed article topic keywords
    art_specific_emb = embed_keyword_list(article["topics"]["specific"])
    art_generic_emb  = embed_keyword_list(article["topics"]["generic"])

    # Specific vs Specific
    if profile_vectors["specific"] is not None:
        specific_score = cosine_similarity(art_specific_emb, profile_vectors["specific"])
    else:
        specific_score = 0.0

    # Generic vs Generic
    if profile_vectors["generic"] is not None:
        generic_score = cosine_similarity(art_generic_emb, profile_vectors["generic"])
    else:
        generic_score = 0.0

    importance = article["importance"] / 10.0

    # Specific match weighted higher — more precise signal
    final = (specific_score * 0.55) + (generic_score * 0.25) + (importance * 0.20)

    return {
        "specific_score": round(specific_score, 3),
        "generic_score":  round(generic_score, 3),
        "importance":     round(importance, 3),
        "final":          round(final, 3)
    }


