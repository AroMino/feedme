def main():
    print("=" * 70)
    print("  SEMANTIC MATCHING V4 — STRUCTURED PROFILE + TOPIC-LEVEL MATCHING")
    print("=" * 70)

    # ── Step 1: Structure profile ──
    print(f"\n👤 Raw interests: {USER_INTERESTS_RAW}")
    print("\n🧠 Structuring profile via Groq...")
    structured = structure_interests(USER_INTERESTS_RAW)
    print(f"   ✅ Specific  : {structured.get('specific', [])}")
    print(f"   🔵 Generic   : {structured.get('generic', [])}")
    print(f"   ❌ Redundant : {structured.get('redundant', [])}")

    # ── Step 2: Enrich non-redundant interests ──
    print("\n🔑 Enriching interests via Groq...\n")
    enriched = {}
    all_active = structured.get("specific", []) + structured.get("generic", [])

    for interest in all_active:
        kind = "specific" if interest in structured.get("specific", []) else "generic"
        keywords = enrich_interest(interest, kind)
        enriched[interest] = keywords
        print(f"   [{kind}] '{interest}'\n   → {keywords[:100]}...\n")

    # ── Step 3: Build profile vectors ──
    print("⏳ Building profile vectors (Gemini embeddings)...")
    profile_vectors = build_profile_vectors(structured, enriched)
    for kind, vec in profile_vectors.items():
        status = f"{len(vec)} dims" if vec is not None else "none"
        print(f"   ✓ {kind} profile vector : {status}")

    # ── Step 4: Score articles ──
    print("\n⏳ Scoring articles...\n")
    print("-" * 70)

    results = []
    for article in ARTICLES:
        scores = score_article(article, profile_vectors)
        results.append({**article, **scores})

    # ── Step 5: Fixed thresholds ──
    THRESH_HIGH = 0.72
    THRESH_LOW  = 0.62

    print(f"📐 Fixed thresholds")
    print(f"   🟢 Highly relevant : >= {THRESH_HIGH}")
    print(f"   🟡 Relevant        : >= {THRESH_LOW}")
    print(f"   🔴 Filtered        :  < {THRESH_LOW}\n")

    # ── Step 6: Display results ──
    results_sorted = sorted(results, key=lambda x: x["final"], reverse=True)

    print(f"{'Final':<7} {'Specific':<10} {'Generic':<10} {'Import':<8} {'Label':<20} Title")
    print("-" * 70)

    for r in results_sorted:
        f = r["final"]
        if f >= THRESH_HIGH:
            label = "🟢 highly relevant"
        elif f >= THRESH_LOW:
            label = "🟡 relevant"
        else:
            label = "🔴 not relevant"

        title = r["title"][:28] + "..." if len(r["title"]) > 28 else r["title"]
        print(f"{f:<7} {r['specific_score']:<10} {r['generic_score']:<10} {r['importance']:<8} {label:<20} {title}")
        print(f"        Expected: {r['expected']}\n")

    # ── Summary ──
    print("-" * 70)
    shown   = [r for r in results if r["final"] >= THRESH_LOW]
    filtered = [r for r in results if r["final"] < THRESH_LOW]

    print(f"\n📊 Summary:")
    print(f"   🟢 Shown in feed : {len(shown)} / {len(ARTICLES)}")
    print(f"   🔴 Filtered out  : {len(filtered)} / {len(ARTICLES)}")

    print(f"\n✅ User feed:")
    for r in sorted(shown, key=lambda x: x["final"], reverse=True):
        print(f"   {r['final']}  [{r['specific_score']} spec / {r['generic_score']} gen]  {r['title']}")

    print(f"\n❌ Filtered articles:")
    for r in sorted(filtered, key=lambda x: x["final"], reverse=True):
        print(f"   {r['final']}  [{r['specific_score']} spec / {r['generic_score']} gen]  {r['title']}")


if __name__ == "__main__":
    main()